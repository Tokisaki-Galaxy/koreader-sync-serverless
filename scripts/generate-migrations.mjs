import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDir = join(root, "migrations");
const outputPath = join(root, "src", "migrations-bundle.ts");

const files = readdirSync(migrationsDir)
  .filter((file) => file.endsWith(".sql"))
  .sort();

const entries = files.map((file) => {
  const version = file.replace(/\.sql$/, "");
  const sql = readFileSync(join(migrationsDir, file), "utf8")
    .replace(/\\/g, "\\\\")
    .replace(/`/g, "\\`")
    .replace(/\$\{/g, "\\${");
  return `  {\n    version: ${JSON.stringify(version)},\n    sql: \`${sql}\`,\n  },`;
});

const output = `// Generated by scripts/generate-migrations.mjs. Do not edit by hand.
import type { Migration } from "./migrations";

export const MIGRATIONS: Migration[] = [
${entries.join("\n")}
];
`;

writeFileSync(outputPath, output, "utf8");
console.log(`Wrote ${outputPath} with ${files.length} migrations.`);
